-- Employee sign-up table for Supabase Postgres.
-- Mirrors body.models.Body_signup (migrations 0001-0009), so Django can read and write it.
-- If you create the table with this script, mark the migrations as applied afterwards:
--   python manage.py migrate body --fake

CREATE TABLE IF NOT EXISTS public.employee_info (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(100) NOT NULL,
    phone_number   varchar(32)  NOT NULL DEFAULT '',
    age            integer      NOT NULL,
    department     varchar(100) NOT NULL,
    position       varchar(100) NOT NULL,
    residence      varchar(100) NOT NULL,
    gender         varchar(10)  NOT NULL,
    complications  text         NOT NULL,
    employee_id    varchar(200) NOT NULL UNIQUE,
    photo          varchar(100) NOT NULL DEFAULT '',  -- path in the employee-photos bucket
    password_hash  varchar(128) NOT NULL DEFAULT '',  -- Django password hash, never plain text
    is_hr_access   boolean      NOT NULL DEFAULT false
);

-- Django's pattern index for LIKE / icontains lookups on the unique column.
CREATE INDEX IF NOT EXISTS employee_info_employee_id_like
    ON public.employee_info (employee_id varchar_pattern_ops);

-- Block the public Data API (anon / publishable key) from reading employee records.
-- Django connects as the postgres role, which bypasses row level security.
ALTER TABLE public.employee_info ENABLE ROW LEVEL SECURITY;
